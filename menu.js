/* =========================
   RENDER MENU
========================= */

const categoryNav = document.getElementById("category-nav");
const menuContainer = document.getElementById("menu-container");
const searchInput = document.getElementById("menu-search");

let currentCategory = "Tutti";


/* CATEGORY BUTTONS */

function renderCategories() {

  categoryNav.innerHTML = "";

  const allButton = document.createElement("button");

  allButton.className = "category-button active";
  allButton.textContent = "Tutti";

  allButton.onclick = () => {
    currentCategory = "Tutti";

    document
      .querySelectorAll(".category-button")
      .forEach(button => button.classList.remove("active"));

    allButton.classList.add("active");

    renderMenu();
  };

  categoryNav.appendChild(allButton);


  menuData.forEach(category => {

    const button = document.createElement("button");

    button.className = "category-button";

    button.textContent = category.category;

    button.onclick = () => {

      currentCategory = category.category;

      document
        .querySelectorAll(".category-button")
        .forEach(button => button.classList.remove("active"));

      button.classList.add("active");

      renderMenu();

    };

    categoryNav.appendChild(button);

  });

}


/* MENU */

function renderMenu() {

  const search =
    searchInput.value
      .trim()
      .toLowerCase();


  let categories = menuData;


  if (currentCategory !== "Tutti") {

    categories = menuData.filter(
      category =>
        category.category === currentCategory
    );

  }


  menuContainer.innerHTML = "";


  categories.forEach(category => {

    const filteredItems =
      category.items.filter(item => {

        const text = (
          item.name +
          " " +
          item.description
        ).toLowerCase();

        return text.includes(search);

      });


    if (!filteredItems.length) {
      return;
    }


    const section =
      document.createElement("section");

    section.className = "menu-category";


    section.innerHTML = `

      <div class="menu-category-title">

        <div>

          <h3>
            ${category.category}
          </h3>

        </div>

        <span>
          ${category.subtitle}
        </span>

      </div>

      <div class="menu-items"></div>

    `;


    const itemsContainer =
      section.querySelector(".menu-items");


    filteredItems.forEach(item => {

      const article =
        document.createElement("article");

      article.className = "menu-item";


      article.innerHTML = `

        <div class="menu-number">
          ${item.number}
        </div>

        <div class="menu-item-main">

          <h4>
            ${item.name}
          </h4>

          <p>
            ${item.description}
          </p>

          ${
            item.tag
              ? `<span class="menu-tag">${item.tag}</span>`
              : ""
          }

        </div>

        <div class="menu-price">
          ${item.price}
        </div>

      `;


      itemsContainer.appendChild(article);

    });


    menuContainer.appendChild(section);

  });


  if (!menuContainer.children.length) {

    menuContainer.innerHTML = `

      <div style="
        padding:80px 20px;
        text-align:center;
        color:#888;
      ">

        Nessun piatto trovato.

      </div>

    `;

  }

}


/* SEARCH */

searchInput.addEventListener(
  "input",
  renderMenu
);


/* START */

renderCategories();
renderMenu();
